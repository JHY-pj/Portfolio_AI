# 10. 다음 Node 결정
# =========================================================

def decide_next_node(state: RobotState):

    category = state.get(
        "category",
        "ambiguous"
    )

    needs_clarification = state.get(
        "needs_clarification",
        False
    )


    # 정말 질문이 먼저 필요한 경우
    if needs_clarification:

        return "clarification"


    if category == "civil":

        return "civil_response"


    if category == "criminal":

        return "criminal_response"


    if category == "general":

        return "general_response"


    return "clarification"


