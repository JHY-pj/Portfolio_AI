class ConversationAnalysis(BaseModel):

    category: Literal[
        "civil",
        "criminal",
        "ambiguous",
        "general"
    ] = Field(
        description=(
            "현재 사용자가 원하는 도움의 영역. "
            "특정 키워드가 아니라 전체 문맥과 "
            "사용자의 목적을 기준으로 판단"
        )
    )

    intent: str = Field(
        description=(
            "현재 사용자가 가장 알고 싶거나 "
            "해결하고 싶은 내용"
        )
    )

    emotion: str = Field(
        description=(
            "사용자가 명확하게 표현한 감정. "
            "추측하지 말고 확인되지 않으면 '불명확'"
        )
    )

    known_facts: List[str] = Field(
        default_factory=list,
        description=(
            "사용자가 직접 말해서 "
            "현재까지 확인된 사건 사실"
        )
    )

    missing_information: List[str] = Field(
        default_factory=list,
        description=(
            "현재 사용자의 목적을 안내하는 데 "
            "추가 확인하면 도움이 되는 정보"
        )
    )

    needs_clarification: bool = Field(
        description=(
            "현재 유용한 답변을 하기 전에 "
            "추가 질문이 반드시 필요한지 여부"
        )
    )

    clarification_question: Optional[str] = Field(
        default=None,
        description=(
            "추가 확인이 필요한 경우 "
            "사용자에게 할 가장 중요한 질문 하나"
        )
    )


analysis_llm = llm.with_structured_output(
    ConversationAnalysis
)


# =========================================================
# 4. LangGraph State
# =========================================================

class RobotState(TypedDict, total=False):

    question: str

    conversation_context: str

    category: str

    intent: str

    emotion: str

    known_facts: List[str]

    missing_information: List[str]

    needs_clarification: bool

    clarification_question: str

    answer: str


