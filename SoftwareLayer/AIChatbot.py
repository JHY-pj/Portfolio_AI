# 13. 대화를 텍스트로 변환
# =========================================================

def conversation_to_text(
    messages: List[Dict[str, str]]
):

    lines = []


    for message in messages:

        if message["role"] == "user":

            speaker = "사용자"

        else:

            speaker = "민사 챗봇"


        lines.append(
            f"[{speaker}]"
        )

        lines.append(
            message["content"]
        )

        lines.append("")


    return "\n".join(
        lines
    )


